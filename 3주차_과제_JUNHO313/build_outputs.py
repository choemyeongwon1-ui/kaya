def art(name, jo, mst=None):
    hits = [a for a in ARTICLES if a["법령명"] == name and a["조"] == jo
            and (mst is None or a["MST"] == mst)]
    if not hits:
        raise SystemExit(f"raw 에 없음: {name} {jo} {mst or ''}")
    return hits[0]


def num(s):
    """'1천500' → 1500, '1,200' → 1200"""
    s = s.replace(",", "").replace(" ", "")
    if "천" in s:
        a, b = s.split("천")
        return int(a) * 1000 + (int(b) if b else 0)
    return int(s)


N = r"(\d[\d,]*(?:천\d*)?)"


def value_after(text, label, pattern):
    # 조례·시행령의 '각 호' 는 "N. 라벨 : 값" 형태 — 라벨 바로 뒤의 값만 읽는다
    m = re.search(re.escape(label) + r"\s*[:：]\s*" + pattern, text)
    return m


def excerpt(a, needle, width=170):
    t = a["원문"].replace("\n", " ")
    i = t.find(needle)
    if i < 0:
        raise SystemExit(f"원문에 '{needle}' 없음: {a['법령명']} {a['조']}")
    start = max(0, i - 20)
    s = t[start:start + width].strip()
    return ("…" if start else "") + s + ("…" if start + width < len(t) else "")


def ident(a):
    kind = "자치법규ID" if len(a["ID"]) > 6 else "법령ID"
    return f"{kind} {a['ID']} / MST {a['MST']}"


def ymd(s):
    return f"{s[:4]}-{s[4:6]}-{s[6:]}"


